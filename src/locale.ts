const englishPresetNames: Record<string, string> = {
  acetone: 'Acetone',
  water: 'Distilled water',
  milk: 'Whole milk',
  blood: 'Whole blood (37 °C)',
  'olive-oil': 'Olive oil',
  sae30: 'SAE 30 motor oil',
  cornstarch: 'Cornstarch suspension',
  glycerin: 'Pure glycerin',
  honey: 'Honey',
  ketchup: 'Industrial ketchup',
  'peanut-butter': 'Peanut butter',
  'cement-slurry': 'Cement slurry',
};

export function presetName(language: Language, id: string, original: string): string {
  return language === 'en' ? englishPresetNames[id] ?? original : original;
}

const readings = {
  en: [0, 1, 2, 3].map((digits) => new Intl.NumberFormat('en-US', { maximumFractionDigits: digits })),
  it: [0, 1, 2, 3].map((digits) => new Intl.NumberFormat('it-IT', { maximumFractionDigits: digits })),
};

export function formatReading(language: Language, value: number, digits: 0 | 1 | 2 | 3): string {
  return readings[language][digits].format(value);
}

export function formatInput(language: Language, value: number): string {
  return language === 'it' ? String(value).replace('.', ',') : String(value);
}

export function readPreference(key: string): string | null {
  try {
    return window.localStorage.getItem(key);
  } catch {
    return null;
  }
}

export function savePreference(key: string, value: string): void {
  try {
    window.localStorage.setItem(key, value);
  } catch {
    // Preferences still work for the current session.
  }
}
